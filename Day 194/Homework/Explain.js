// 1. Big O Notation რა არის?
// Big O Notation არის მათემატიკური გზა, რომელიც აღწერს ალგორითმის დროით (ან მეხსიერების) სირთულეს იმის მიხედვით, თუ როგორ იზრდება ალგორითმის შესრულების დრო შეყვანის მონაცემების ზომის (n) ზრდასთან ერთად.
// მარტივად რომ ვთქვათ — ის გვიჩვენებს, რამდენად კარგად იქცევა ალგორითმი დიდი მონაცემებისას. გამოიყენება იმისთვის, რომ შევადაროთ სხვადასხვა ალგორითმები და ავარჩიოთ ყველაზე ეფექტური, განსაკუთრებით დიდი n-ის შემთხვევაში.

