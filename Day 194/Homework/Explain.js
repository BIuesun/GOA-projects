// O(1) — Constant time (ყველაზე სწრაფი)
// O(log n)
// O(n)
// O(n log n)
// O(n²) — ყველაზე ნელი ამ სიაში



// 3.
for(let i = 0; i < n; i++) {
    console.log(i);
}
